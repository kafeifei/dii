// What every importer stage shares: the pinned sources, the download cache, the official strings
// and the writer for src/data/d2x.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '../..');
const CACHE = path.join(ROOT, 'tools/.d2cache');
export const DATA = 'https://raw.githubusercontent.com/blizzhackers/d2data/fc469993502d0498809b9fc1af140ee2a9eb8902/json/';
export const STR = 'https://raw.githubusercontent.com/WalterCouto/D2CE/c246509f385790462979004aeeaf7a47696ed605/source/res/TXT/local/lng/strings/';
/** D2R 2.7, the last tables before the Warlock expansion: the treasure classes are its (tools/d2/treasure.mjs); the validation report compares against the rest */
export const REF27 = 'https://raw.githubusercontent.com/blizzhackers/d2data/0ec7650fd7641762339ea9ea44c03dec89f1777b/json/';
const PREFIX = { [DATA]: 'data', [STR]: 'str', [REF27]: 'ref27' };

export async function load(base, name) {
  fs.mkdirSync(CACHE, { recursive: true });
  const file = path.join(CACHE, `${PREFIX[base]}-${name}.json`);
  if (!fs.existsSync(file)) {
    const r = await fetch(base + name + '.json');
    if (!r.ok) throw new Error(`${name}: HTTP ${r.status}`);
    fs.writeFileSync(file, await r.text());
  }
  return JSON.parse(fs.readFileSync(file, 'utf8').replace(/^﻿/, ''));
}
export const rows = (x) => (Array.isArray(x) ? x : Object.values(x));
/** several d2data tables at once, by name */
export const tables = (...names) => Promise.all(names.map((n) => load(DATA, n)));

/** the official strings of some D2CE string files, by key (the item files share no keys) */
export async function strings(...files) {
  const zh = {};
  const en = {};
  for (const t of await Promise.all(files.map((f) => load(STR, f)))) {
    for (const e of rows(t)) {
      zh[e.Key] = e.zhCN;
      en[e.Key] = e.enUS;
    }
  }
  return { zh, en };
}

/** the numbers i in 1..max for which a row has column col(i) ("prop1", "prop2", …) */
export function numbered(r, max, col) {
  const out = [];
  for (let i = 1; i <= max; i++) if (r[col(i)] !== undefined && r[col(i)] !== '') out.push(i);
  return out;
}

const D2X = path.join(ROOT, 'src/data/d2x');
const HEAD = `// Generated by tools/d2-import.mjs from Diablo II: Resurrected's data tables. Do not edit.\n`;
export const json = (v) => JSON.stringify(v);
export const list = (arr) => `[\n${arr.map((x) => `  ${json(x)},`).join('\n')}\n]`;
export const record = (obj) => `{\n${Object.entries(obj).map(([k, v]) => `  ${json(k)}: ${json(v)},`).join('\n')}\n}`;
/** writes src/data/d2x/<file> under the generated-file header */
export function writeD2x(file, body) {
  fs.mkdirSync(D2X, { recursive: true });
  fs.writeFileSync(path.join(D2X, file), HEAD + body);
  console.log(`d2x/${file}: ${(body.length / 1024).toFixed(0)} KB`);
}
